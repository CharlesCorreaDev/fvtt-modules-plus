#!/usr/bin/env python3
"""
Foundry VTT Content & Macro Humanizer & Unicode Sanitizer
Author: GM Charles Corrêa (Master of Foundry VTT)

Cleans zero-width characters, typographic curly quotes, and AI commentary
from macros, JSON compendiums, journal files, and scripts.
"""

import sys
import os
import re
import argparse

ZERO_WIDTH_CHARS = [
    '\u200b',  # Zero-width space
    '\u200c',  # Zero-width non-joiner
    '\u200d',  # Zero-width joiner
    '\ufeff',  # Byte order mark / zero-width no-break space
    '\u200e',  # Left-to-right mark
    '\u200f',  # Right-to-left mark
    '\u2060',  # Word joiner
]

AI_HEADER_PATTERNS = [
    r'^\s*//\s*(?:Generated by|Created by|Author:\s*AI|ChatGPT|Claude|Assistant).*$\n?',
    r'^\s*/\*\*[\s\S]*?(?:Generated by|AI Assistant|Foundry VTT Macro generated)[\s\S]*?\*/\n?',
    r'<!--\s*(?:cid|openai|anthropic|generator):.*?-->\n?',
]

CURLY_QUOTES = {
    '\u201c': '"',
    '\u201d': '"',
    '\u2018': "'",
    '\u2019': "'",
    '\u00a0': ' ',  # Non-breaking space to regular space
}

# Comprehensive regex for all Unicode emojis and pictographic symbols
ALL_EMOJIS_REGEX = re.compile(
    r'[\U00010000-\U0010ffff\u2600-\u26FF\u2700-\u27BF\uFE0F\u200D]',
    flags=re.UNICODE
)

def sanitize_content(text: str, is_code: bool = True, keep_emojis: bool = False) -> tuple[str, int]:
    count_cleaned = 0
    
    # 1. Strip zero-width chars
    for zwc in ZERO_WIDTH_CHARS:
        if zwc in text:
            occurrences = text.count(zwc)
            count_cleaned += occurrences
            text = text.replace(zwc, '')
            
    # 2. Normalize curly quotes
    for curly, straight in CURLY_QUOTES.items():
        if curly in text:
            occurrences = text.count(curly)
            count_cleaned += occurrences
            text = text.replace(curly, straight)
            
    # 3. Strip AI headers in code
    if is_code:
        for pat in AI_HEADER_PATTERNS:
            matches = len(re.findall(pat, text, flags=re.MULTILINE))
            if matches:
                count_cleaned += matches
                text = re.sub(pat, '', text, flags=re.MULTILINE)
                
    # 4. Strip all emojis by default unless keep_emojis is explicitly requested
    if not keep_emojis:
        emoji_matches = len(re.findall(ALL_EMOJIS_REGEX, text))
        if emoji_matches:
            count_cleaned += emoji_matches
            text = re.sub(ALL_EMOJIS_REGEX, '', text)
            text = re.sub(r'[ \t]{2,}', ' ', text)
                
    return text, count_cleaned

def main():
    parser = argparse.ArgumentParser(description="Sanitize and humanize Foundry VTT files.")
    parser.add_argument("path", help="File or directory path to sanitize")
    parser.add_argument("--dry-run", action="store_true", help="Report issues without modifying files")
    parser.add_argument("--keep-emojis", action="store_true", help="Keep emojis in text instead of stripping them")
    args = parser.parse_args()

    target = args.path
    if not os.path.exists(target):
        print(f"Error: Target path '{target}' not found.", file=sys.stderr)
        sys.exit(1)

    files_to_process = []
    if os.path.isfile(target):
        files_to_process.append(target)
    else:
        for root, _, files in os.walk(target):
            for f in files:
                if f.endswith(('.js', '.mjs', '.json', '.md', '.html', '.hbs')):
                    files_to_process.append(os.path.join(root, f))

    total_changes = 0
    modified_files = 0

    for file_path in files_to_process:
        try:
            with open(file_path, 'r', encoding='utf-8') as fh:
                content = fh.read()
        except UnicodeDecodeError:
            continue

        is_code = file_path.endswith(('.js', '.mjs', '.json'))
        clean_content, changes = sanitize_content(content, is_code=is_code, keep_emojis=args.keep_emojis)

        if changes > 0:
            modified_files += 1
            total_changes += changes
            print(f"[{'WOULD FIX' if args.dry_run else 'FIXED'}] {file_path}: {changes} marks removed")
            if not args.dry_run:
                with open(file_path, 'w', encoding='utf-8', newline='\n') as fh:
                    fh.write(clean_content)

    print(f"\nDone. Processed {len(files_to_process)} files. Modified: {modified_files}. Total marks cleaned: {total_changes}.")

if __name__ == "__main__":
    main()
