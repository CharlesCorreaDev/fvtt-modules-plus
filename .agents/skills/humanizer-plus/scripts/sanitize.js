#!/usr/bin/env node
/**
 * Humanizer Plus - Unicode & Provenance Sanitizer (Node.js)
 * Author: Charles Corrêa
 * 
 * Recursively scans and cleans invisible zero-width tracking characters,
 * typographic quotes, and AI headers across files.
 */

import fs from 'fs';
import path from 'path';

const ZERO_WIDTH_CHARS = [
  /\u200b/g, // Zero-width space
  /\u200c/g, // Zero-width non-joiner
  /\u200d/g, // Zero-width joiner
  /\ufeff/g, // Byte order mark / zero-width no-break space
  /\u200e/g, // Left-to-right mark
  /\u200f/g, // Right-to-left mark
  /\u2060/g  // Word joiner
];

const AI_HEADER_PATTERNS = [
  /^\s*\/\/\s*(?:Generated by|Created by|Author:\s*AI|ChatGPT|Claude|Assistant|Copilot|Gemini|Ollama|DeepSeek|Auto-generated).*$\r?\n?/gim,
  /^\s*#\s*(?:Generated by|Created by|Author:\s*AI|ChatGPT|Claude|Assistant|Copilot|Gemini|Ollama|DeepSeek|Auto-generated).*$\r?\n?/gim,
  /^\s*\/\*\*[\s\S]*?(?:Generated by|AI Assistant|Copilot|ChatGPT|Claude|Foundry VTT Macro generated)[\s\S]*?\*\/\r?\n?/gim,
  /<!--\s*(?:cid|openai|anthropic|generator|ai_model|prompt):.*?-->\r?\n?/gim
];

const CURLY_QUOTES = [
  [/\u201c/g, '"'],
  [/\u201d/g, '"'],
  [/\u2018/g, "'"],
  [/\u2019/g, "'"],
  [/\u00a0/g, ' '] // Non-breaking space to regular space
];

// Regex abrangente para todos os emojis Unicode (Extended Pictographic, Symbols, Dingbats, Modifiers, Flags, etc.)
const ALL_EMOJIS_REGEX = /(?:\p{Extended_Pictographic}|\p{Emoji_Presentation}|\p{Emoji_Modifier_Base}|\p{Emoji_Modifier}|\p{Regional_Indicator}|\uFE0F|\u200D|[\u2600-\u26FF\u2700-\u27BF])/gu;

export function sanitizeText(text, isCode = false, options = {}) {
  let countCleaned = 0;

  for (const regex of ZERO_WIDTH_CHARS) {
    const matches = text.match(regex);
    if (matches) {
      countCleaned += matches.length;
      text = text.replace(regex, '');
    }
  }

  for (const [regex, replacement] of CURLY_QUOTES) {
    const matches = text.match(regex);
    if (matches) {
      countCleaned += matches.length;
      text = text.replace(regex, replacement);
    }
  }

  if (isCode) {
    for (const regex of AI_HEADER_PATTERNS) {
      const matches = text.match(regex);
      if (matches) {
        countCleaned += matches.length;
        text = text.replace(regex, '');
      }
    }
  }

  // Remoção padrão de todo e qualquer emoji, SALVO se o usuário solicitar explicitamente mantê-los (options.keepEmojis = true)
  if (!options.keepEmojis) {
    const emojiMatches = text.match(ALL_EMOJIS_REGEX);
    if (emojiMatches) {
      countCleaned += emojiMatches.length;
      // Remove todos os emojis e normaliza múltiplos espaços residuais
      text = text.replace(ALL_EMOJIS_REGEX, '').replace(/[ \t]{2,}/g, ' ');
    }
  }

  return { text, countCleaned };
}

function processPath(targetPath, dryRun = false, options = {}) {
  if (!fs.existsSync(targetPath)) {
    console.error(`Error: Target path '${targetPath}' not found.`);
    process.exit(1);
  }

  const stat = fs.statSync(targetPath);
  const files = [];

  if (stat.isFile()) {
    files.push(targetPath);
  } else {
    function walk(dir) {
      for (const item of fs.readdirSync(dir)) {
        if (item === 'node_modules' || item === '.git') continue;
        const full = path.join(dir, item);
        const s = fs.statSync(full);
        if (s.isDirectory()) {
          walk(full);
        } else if (/\.(js|mjs|cjs|ts|jsx|tsx|json|md|html|hbs|txt|py|php)$/i.test(item)) {
          files.push(full);
        }
      }
    }
    walk(targetPath);
  }

  let totalChanges = 0;
  let modifiedFiles = 0;

  for (const file of files) {
    try {
      const original = fs.readFileSync(file, 'utf8');
      const isCode = /\.(js|mjs|cjs|ts|jsx|tsx|json|py|php)$/i.test(file);
      const { text, countCleaned } = sanitizeText(original, isCode, options);

      if (countCleaned > 0) {
        modifiedFiles++;
        totalChanges += countCleaned;
        console.log(`[${dryRun ? 'WOULD FIX' : 'FIXED'}] ${file}: ${countCleaned} marks removed`);
        if (!dryRun) {
          fs.writeFileSync(file, text, 'utf8');
        }
      }
    } catch (err) {
      console.error(`Skipping ${file}: ${err.message}`);
    }
  }

  console.log(`\nHumanizer Plus Sanitizer: Processed ${files.length} files. Modified: ${modifiedFiles}. Total marks cleaned: ${totalChanges}.`);
}

import { fileURLToPath } from 'url';

const isDirectRun = process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1]);

if (isDirectRun) {
  const args = process.argv.slice(2);
  const dryRun = args.includes('--dry-run');
  const keepEmojis = args.includes('--keep-emojis');
  const target = args.find(a => !a.startsWith('--'));

  if (!target) {
    console.log("Usage: node scripts/sanitize.js <path-to-file-or-dir> [--dry-run] [--keep-emojis]");
    console.log("Note: All emojis are stripped by default unless --keep-emojis is explicitly specified.");
    process.exit(0);
  }

  processPath(target, dryRun, { keepEmojis });
}
